// Turns assets/butterfly/*.svg into src/components/butterflyMoods.ts:  node scripts/build-butterflies.cjs
// Each mood is split in two layers (wings / body) so the app can flap the wings natively.
const fs = require('fs'), path = require('path');
const dir = path.resolve(__dirname, '../assets/butterfly');
const MOODS = { happy: 'دڵخۆش', angry: 'تووڕە', sad: 'خەمبار', surprised: 'سەرسام', sleepy: 'خەواڵوو', calm: 'ئاسایی' };
const out = {};
for (const mood of Object.keys(MOODS)) {
  const svg = fs.readFileSync(path.join(dir, `butterfly-${mood}.svg`), 'utf8').trim();
  const start = svg.indexOf('<g class="left-wing">');
  let depth = 0, end = -1;
  const re = /<g[\s>]|<\/g>/g; re.lastIndex = start;
  for (let m; (m = re.exec(svg)); ) {
    depth += m[0].startsWith('</') ? -1 : 1;
    if (depth === 0) { const closing = svg.indexOf('</g>', m.index) + 4; if (svg.slice(closing).startsWith('<g class="right-wing">')) { re.lastIndex = closing; continue; } end = closing; break; }
  }
  if (start < 0 || end < 0) throw new Error('cannot split ' + mood);
  const head = svg.slice(0, start), wings = svg.slice(start, end), body = svg.slice(end);
  out[mood] = { label: MOODS[mood], wings: head + wings + '</svg>', body: head + body };
}
fs.writeFileSync(path.resolve(__dirname, '../src/components/butterflyMoods.ts'),
  `// Generated by scripts/build-butterflies.cjs from assets/butterfly/*.svg. Do not edit by hand.\nexport type Mood = ${Object.keys(MOODS).map(m => `'${m}'`).join(' | ')};\nexport const BUTTERFLY_MOODS: Record<Mood, { label: string; wings: string; body: string }> = ${JSON.stringify(out, null, 2)};\n`);
console.log('moods:', Object.keys(out).join(', '));
