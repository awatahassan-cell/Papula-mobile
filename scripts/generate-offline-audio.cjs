const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { catalog, DEFAULT_VOICE, MODEL } = require('./offline-audio-catalog.cjs');
const root = path.resolve(__dirname, '..');
const directory = path.join(root, 'assets/audio/papula-v2');
const manifestPath = path.join(directory, 'manifest.json');
const digest = text => crypto.createHash('sha256').update(text).digest('hex');
const cleanWord = text => text.replace(/\uFE0F/gu, '').replace(/^[\p{P}\p{S}]+|[\p{P}\p{S}]+$/gu, '');

function plan(entries) {
  const primary = entries.filter(item => item.category !== 'word');
  const words = new Map();
  // Optional entries never become the parent of a word: that would move an already-bought word into a new batch.
  for (const entry of primary.filter(item => !item.optional)) for (const match of entry.text.matchAll(/\S+/gu)) {
    const word = cleanWord(match[0]);
    if (word && !words.has(word)) words.set(word, { key: entry.key, start: match.index + match[0].indexOf(word), end: match.index + match[0].indexOf(word) + word.length });
  }
  // Optional recordings are queued after everything else so earlier batches keep exactly the same contents.
  const derived = [], generate = primary.filter(item => !item.optional), optional = primary.filter(item => item.optional);
  for (const entry of entries.filter(item => item.category === 'word')) {
    const parent = words.get(entry.text);
    if (parent) derived.push({ entry, parent }); else generate.push(entry);
  }
  generate.push(...optional);
  // Keep isolated letter sounds in independent requests. Other phrases share
  // a new recording with exact character timestamps, never an old cache file.
  const batches = [];
  let batch = [];
  for (const entry of generate) {
    if (entry.category === 'letter' || entry.category === 'syllable') {
      // Isolated letter sounds and syllables are requested alone so they are read as a bare sound.
      if (batch.length) { batches.push(batch); batch = []; }
      batches.push([entry]);
    } else if (entry.optional && batch.length && !batch[0].optional) {
      batches.push(batch); batch = [entry];
    } else {
      if (batch.reduce((sum, item) => sum + item.narrationText.length + 2, 0) + entry.narrationText.length > 1100) { batches.push(batch); batch = []; }
      batch.push(entry);
    }
  }
  if (batch.length) batches.push(batch);
  return { batches, derived };
}

function locateWords(text, alignment, cursor = 0) {
  const spoken = alignment.characters.join('');
  const indices = [];
  alignment.characters.forEach((character, index) => { for (let i = 0; i < character.length; i++) indices.push(index); });
  const timings = [];
  for (const match of text.matchAll(/\S+/gu)) {
    const word = cleanWord(match[0]);
    if (!word) continue;
    const at = spoken.indexOf(word, cursor);
    if (at < 0) throw Error('Alignment does not contain reading word: ' + match[0]);
    const from = alignment.character_start_times_seconds[indices[at]];
    const to = alignment.character_end_times_seconds[indices[at + word.length - 1]];
    if (!Number.isFinite(from) || !Number.isFinite(to) || to < from) throw Error('Invalid alignment');
    timings.push({ start: match.index, end: match.index + match[0].length, from, to });
    cursor = at + word.length;
  }
  return { timings, cursor };
}

function writeModule(records) {
  const lines = Object.entries(records).map(([key, row]) => `  ${JSON.stringify(key)}: { source: require('../../assets/audio/papula-v2/${row.file}'), start: ${row.start}, end: ${row.end}, timings: ${JSON.stringify(row.timings)} },`);
  fs.writeFileSync(path.join(root, 'src/data/offlineAudio.ts'), `// Generated by scripts/generate-offline-audio.cjs. Papula voice only.\nexport type OfflineTrack = { source: number | string; start: number; end: number; timings: {start:number;end:number;from:number;to:number}[] };\nexport const OFFLINE_AUDIO: Record<string, OfflineTrack> = {\n${lines.join('\n')}\n};\n`);
}

async function main() {
  const entries = catalog();
  const { batches, derived } = plan(entries);
  fs.mkdirSync(directory, { recursive: true });
  const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : { voiceId: DEFAULT_VOICE, model: MODEL, createdAt: new Date().toISOString(), batches: {}, records: {} };
  const covered = batch => batch.every(item => manifest.records[item.key]); // already recorded under an earlier batching
  const pending = batches.filter(batch => { const id = digest(batch.map(item => item.key).join('\n')); return !manifest.batches[id] && !covered(batch) && !fs.existsSync(path.join(directory, id + '.alignment.json')); });
  const characters = pending.reduce((sum, batch) => sum + batch.map(item => item.narrationText).join('\n\n').length, 0);
  console.log(JSON.stringify({ tracks: entries.length, requests: pending.length, characters, derivedWords: derived.length }));
  if (!process.argv.includes('--generate') && !process.argv.includes('--finalize')) return;
  if (process.argv.includes('--finalize') && pending.length) throw Error('Generation is incomplete; finalize cannot request missing recordings.');
  const env = fs.existsSync(path.join(root, '.env.local')) ? fs.readFileSync(path.join(root, '.env.local'), 'utf8') : '';
  const key = process.env.ELEVENLABS_API_KEY || env.match(/^(?:ELEVENLABS_API_KEY|EXPO_PUBLIC_ELEVENLABS_API_KEY)=(.*)$/m)?.[1]?.trim().replace(/^['"]|['"]$/g, '');
  if (pending.length && !key) throw Error('No ElevenLabs key configured');
  const request = async (url, options = {}) => {
    const response = await fetch('https://api.elevenlabs.io' + url, { ...options, headers: { 'xi-api-key': key, ...options.headers }, signal: AbortSignal.timeout(180000) });
    if (!response.ok) { const body = await response.json().catch(() => ({})); throw Error(`ElevenLabs ${response.status}: ${body.detail?.status || body.detail?.message || 'Request rejected'}`); }
    return response;
  };
  if (pending.length) {
    const subscription = await (await request('/v1/user/subscription')).json();
    const remaining = subscription.character_limit - subscription.character_count;
    if (characters > remaining) throw Error(`Insufficient credits: ${characters} characters required; ${remaining} remaining. No generation started.`);
    console.log(JSON.stringify({ creditsRemaining: remaining, estimatedCharacters: characters }));
  }
  // Sequential generation avoids exceeding Starter concurrency and keeps each
  // completed batch durable. Re-running only resumes this fresh recording set.
  for (const [index, batch] of batches.entries()) {
    const id = digest(batch.map(item => item.key).join('\n'));
    if (manifest.batches[id] || covered(batch)) continue;
    const text = batch.map(item => item.narrationText).join('\n\n');
    const savedPath = path.join(directory, id + '.alignment.json');
    let saved;
    if (fs.existsSync(savedPath)) saved = JSON.parse(fs.readFileSync(savedPath, 'utf8'));
    else {
    const result = await (await request(`/v1/text-to-speech/${DEFAULT_VOICE}/with-timestamps?output_format=mp3_44100_128`, {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ text, model_id: MODEL, language_code: 'ckb', apply_text_normalization: 'off' }),
    })).json();
    const bytes = Buffer.from(result.audio_base64 || '', 'base64');
    if (bytes.length < 100 || !(bytes.toString('ascii', 0, 3) === 'ID3' || bytes[0] === 255 && (bytes[1] & 224) === 224)) throw Error('Invalid MP3 returned');
    const file = digest(bytes) + '.mp3';
    fs.writeFileSync(path.join(directory, file), bytes);
    const alignment = result.normalized_alignment || result.alignment;
    if (!alignment?.characters?.length) throw Error('Missing alignment');
    // Save the paid response before mapping so an alignment repair never
    // silently purchases the same batch twice.
    saved = { file, alignment, bytes: bytes.length, keys: batch.map(item => item.key) };
    fs.writeFileSync(savedPath, JSON.stringify(saved));
    }
    const { file, alignment } = saved;
    let cursor = 0;
    for (const entry of batch) {
      const mapped = locateWords(entry.text, alignment, cursor);
      cursor = mapped.cursor;
      const start = Math.max(0, mapped.timings[0].from - 0.015);
      const end = mapped.timings.at(-1).to;
      manifest.records[entry.key] = { file, start, end, timings: mapped.timings, category: entry.category };
    }
    manifest.batches[id] = { file, bytes: saved.bytes, characters: text.length };
    fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
    writeModule(manifest.records);
    console.log(JSON.stringify({ completed: index + 1, total: batches.length, tracks: Object.keys(manifest.records).length, bytes: saved.bytes }));
  }
  for (const { entry, parent } of derived) {
    const row = manifest.records[parent.key];
    const timing = row.timings.find(item => item.start <= parent.start && item.end >= parent.end);
    if (!timing) throw Error('Missing source timing for ' + entry.text);
    manifest.records[entry.key] = { file: row.file, start: Math.max(row.start, timing.from - 0.015), end: timing.to,
      timings: [{ start: 0, end: entry.text.length, from: timing.from, to: timing.to }], category: 'word' };
  }
  // Tapped words include punctuation; route these exact spellings to the same
  // fresh clip without another billable recording.
  const { narrationCatalog } = require('./story-narration-catalog.cjs');
  const { keyFor } = require('./offline-audio-catalog.cjs');
  const { createLoader } = require('./story-narration-catalog.cjs');
  const { mockLetters } = createLoader()(path.join(root, 'src/data/mockLetters.ts'));
  for (const story of narrationCatalog().stories) for (const page of story.pages) for (const raw of page.textKu.split(/\s+/u)) {
    const letter = mockLetters.find(item => item.glyph === cleanWord(raw));
    const row = manifest.records[keyFor(cleanWord(raw))] || manifest.records[keyFor((letter?.name || cleanWord(raw)) + '[literal-letter-v1]')];
    if (row && !manifest.records[keyFor(raw)]) manifest.records[keyFor(raw)] = { ...row, timings: row.timings.map(item => ({ ...item, start: 0, end: raw.length })) };
  }
  manifest.completedAt = new Date().toISOString();
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
  writeModule(manifest.records);
  console.log(JSON.stringify({ complete: true, tracks: Object.keys(manifest.records).length, files: Object.keys(manifest.batches).length }));
}

module.exports = { plan, locateWords };
if (require.main === module) main().catch(error => { console.error(error.message); process.exitCode = 1; });
