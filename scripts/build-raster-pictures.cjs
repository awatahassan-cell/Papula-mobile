// Turns assets/pictures/NNN-name.webp (or .png) into src/art/rasterPictures.ts. NNN is the number in app-emoji-list.html;
// assets/pictures/index.json says which emoji that number is. Drop a new PNG in the folder and run this script.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'assets/pictures');
const index = JSON.parse(fs.readFileSync(path.join(dir, 'index.json'), 'utf8'));
const files = fs.readdirSync(dir).filter(name => /^\d{3}-.+\.(webp|png)$/.test(name)).sort();
const lines = [];
for (const name of files) {
  const emoji = index[name.slice(0, 3)];
  if (!emoji) { console.warn('no emoji for', name); continue; }
  lines.push(`  ${JSON.stringify(emoji.replace(/️/g, ''))}: require('../../assets/pictures/${name}'),`);
}
fs.writeFileSync(path.join(root, 'src/art/rasterPictures.ts'), `import { ImageSourcePropType } from 'react-native';
/** Painted cartoon pictures that replace the drawn vector for the same emoji. Generated by scripts/build-raster-pictures.cjs. */
export const RASTER: Record<string, ImageSourcePropType> = {
${lines.join('\n')}
};
export const rasterFor = (symbol: string): ImageSourcePropType | undefined => RASTER[symbol.replace(/\\uFE0F/g, '').trim()];
`);
console.log(lines.length, 'pictures');
